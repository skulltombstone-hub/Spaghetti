/**
 * Activity responsible for running imported HTML games.
 *
 * HTML games are stored in the same GameLibrary used by GameMaker games.
 * The importer records a relative entry point such as "index.html", and
 * this activity loads that file directly from the game's private bundle.
 *
 * The WebView is intentionally kept independent from the native GameMaker
 * runner. HTML games communicate with the Android host only through:
 *
 *  - the WebView itself;
 *  - the shared virtual gamepad layout system;
 *  - synthetic DOM keyboard events generated by HtmlKeyState.
 *
 * This keeps the HTML runtime completely separate from ButterscotchNative,
 * while still using the same launcher/library/layout infrastructure.
 */
class HtmlGameActivity : ComponentActivity() {

    companion object {
        const val EXTRA_GAME_ID = "game_id"

        private const val TAG = "HtmlGameActivity"
    }

    private var webView: WebView? = null

    private val pressedKeys = HtmlKeyState()

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        window.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)

        hideSystemBars()

        val gameLibrary = Libraries.loadGameLibrary(applicationContext)
        val layoutLibrary = Libraries.loadLayoutLibrary(applicationContext)

        val gameId = intent
            .getStringExtra(EXTRA_GAME_ID)
            ?.let { value ->
                runCatching {
                    UUID.fromString(value)
                }.getOrNull()
            }

        if (gameId == null) {
            finish()
            return
        }

        val entry = gameLibrary.findById(gameId)

        if (entry == null || entry.gameType !is GameEntry.GameType.Html) {
            finish()
            return
        }

        setContent {
            ButterscotchAndroidTheme {
                HtmlGameContent(
                    entry = entry,
                    library = gameLibrary,
                    layoutLibrary = layoutLibrary,
                    onWebViewCreated = { view ->
                        webView = view
                    },
                    onKeyDown = { vk ->
                        webView?.let { view ->
                            pressedKeys.press(view, vk)
                        }
                    },
                    onKeyUp = { vk ->
                        webView?.let { view ->
                            pressedKeys.release(view, vk)
                        }
                    },
                    onReleaseAllKeys = {
                        webView?.let { view ->
                            pressedKeys.releaseAll(view)
                        } ?: pressedKeys.clear()
                    },
                    onExit = {
                        finish()
                    }
                )
            }
        }
    }

    override fun onPause() {
        pressedKeys.releaseAll(webView)
        super.onPause()
    }

    override fun onDestroy() {
        pressedKeys.releaseAll(webView)

        webView?.apply {
            stopLoading()
            loadUrl("about:blank")
            clearHistory()
            removeAllViews()
            destroy()
        }

        webView = null

        super.onDestroy()
    }

    override fun onWindowFocusChanged(hasFocus: Boolean) {
        super.onWindowFocusChanged(hasFocus)

        if (hasFocus) {
            hideSystemBars()
        }
    }

    private fun hideSystemBars() {
        window.decorView.systemUiVisibility =
            View.SYSTEM_UI_FLAG_FULLSCREEN or
                View.SYSTEM_UI_FLAG_HIDE_NAVIGATION or
                View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY or
                View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN or
                View.SYSTEM_UI_FLAG_LAYOUT_HIDE_NAVIGATION or
                View.SYSTEM_UI_FLAG_LAYOUT_STABLE
    }
}

@SuppressLint("SetJavaScriptEnabled")
@Composable
private fun HtmlGameContent(
    entry: GameEntry,
    library: GameLibrary,
    layoutLibrary: LayoutLibrary,
    onWebViewCreated: (WebView) -> Unit,
    onKeyDown: (Int) -> Unit,
    onKeyUp: (Int) -> Unit,
    onReleaseAllKeys: () -> Unit,
    onExit: () -> Unit
) {
    val gameType = entry.gameType as? GameEntry.GameType.Html
        ?: return

    val rootDirectory = library.bundleDir(entry)
    val entryFile = File(rootDirectory, gameType.entryPoint)

    var showControls by remember {
        mutableStateOf(true)
    }

    var showMenu by remember {
        mutableStateOf(false)
    }

    /*
     * Release every synthetic key whenever the menu is opened.
     * This prevents a held virtual button from remaining pressed while
     * the game is paused behind the menu.
     */
    LaunchedEffect(showMenu) {
        if (showMenu) {
            onReleaseAllKeys()
        }
    }

    /*
     * Release keys when the orientation changes. The layout can be
     * replaced during recomposition, so no old pointer is allowed to
     * keep a key alive.
     */
    val configuration = LocalConfiguration.current

    LaunchedEffect(configuration.orientation) {
        onReleaseAllKeys()
    }

    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(Color.Black)
    ) {
        HtmlWebView(
            entryFile = entryFile,
            onWebViewCreated = onWebViewCreated
        )

        if (showControls && !showMenu) {
            HtmlControls(
                entry = entry,
                layoutLibrary = layoutLibrary,
                onKeyDown = onKeyDown,
                onKeyUp = onKeyUp,
                onMenu = {
                    showMenu = true
                }
            )
        }

        if (showMenu) {
            HtmlMenu(
                controlsVisible = showControls,
                onResume = {
                    showMenu = false
                },
                onToggleControls = {
                    showControls = !showControls
                    showMenu = false
                },
                onExit = {
                    showMenu = false
                    onExit()
                }
            )
        }
    }
}

@SuppressLint("SetJavaScriptEnabled")
@Composable
private fun HtmlWebView(
    entryFile: File,
    onWebViewCreated: (WebView) -> Unit
) {
    AndroidView(
        modifier = Modifier.fillMaxSize(),

        factory = { context ->
            WebView(context).apply {
                onWebViewCreated(this)

                setBackgroundColor(AndroidColor.BLACK)

                settings.apply {
                    javaScriptEnabled = true
                    domStorageEnabled = true
                    databaseEnabled = true

                    allowFileAccess = true
                    allowContentAccess = true

                    /*
                     * HTML games commonly load JavaScript, JSON, images,
                     * audio and other files from sibling directories.
                     */
                    allowFileAccessFromFileURLs = true
                    allowUniversalAccessFromFileURLs = true

                    javaScriptCanOpenWindowsAutomatically = true
                    mediaPlaybackRequiresUserGesture = false

                    useWideViewPort = true
                    loadWithOverviewMode = true

                    builtInZoomControls = false
                    displayZoomControls = false
                    setSupportZoom(false)

                    cacheMode = WebSettings.LOAD_DEFAULT

                    userAgentString =
                        "$userAgentString SpaghettiHTMLRunner/1.0"
                }

                webChromeClient = WebChromeClient()

                webViewClient = object : WebViewClient() {

                    override fun shouldOverrideUrlLoading(
                        view: WebView,
                        request: WebResourceRequest
                    ): Boolean {
                        return when (request.url.scheme?.lowercase()) {
                            "file",
                            "http",
                            "https" -> false

                            else -> true
                        }
                    }
                }

                systemUiVisibility =
                    View.SYSTEM_UI_FLAG_FULLSCREEN or
                        View.SYSTEM_UI_FLAG_HIDE_NAVIGATION or
                        View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY or
                        View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN or
                        View.SYSTEM_UI_FLAG_LAYOUT_HIDE_NAVIGATION or
                        View.SYSTEM_UI_FLAG_LAYOUT_STABLE

                if (entryFile.exists()) {
                    loadUrl(entryFile.toURI().toString())
                }
            }
        }
    )
}

@Composable
private fun HtmlControls(
    entry: GameEntry,
    layoutLibrary: LayoutLibrary,
    onKeyDown: (Int) -> Unit,
    onKeyUp: (Int) -> Unit,
    onMenu: () -> Unit
) {
    val configuration = LocalConfiguration.current

    val isLandscape =
        configuration.orientation == Configuration.ORIENTATION_LANDSCAPE

    val layoutId =
        if (isLandscape) {
            entry.landscapeLayout
        } else {
            entry.portraitLayout
        }

    val fallbackId =
        if (isLandscape) {
            LayoutLibrary.DEFAULT_LANDSCAPE_LAYOUT
        } else {
            LayoutLibrary.DEFAULT_PORTRAIT_LAYOUT
        }

    val layout =
        layoutLibrary.findById(layoutId)
            ?: layoutLibrary.findById(fallbackId)
            ?: return

    BoxWithConstraints(
        modifier = Modifier.fillMaxSize()
    ) {
        layout.elements.forEach { element ->
            when (element) {

                is GamepadElement.Key -> {
                    HtmlKeyButton(
                        element = element,
                        onKeyDown = onKeyDown,
                        onKeyUp = onKeyUp,
                        modifier = placementForElement(element)
                    )
                }

                is GamepadElement.Joystick -> {
                    HtmlJoystick(
                        element = element,
                        onKeyDown = onKeyDown,
                        onKeyUp = onKeyUp,
                        modifier = placementForElement(element)
                    )
                }

                is GamepadElement.Menu -> {
                    HtmlMenuButton(
                        element = element,
                        onClick = onMenu,
                        modifier = placementForElement(element)
                    )
                }

                /*
                 * HTML games are keyboard/DOM-input based in 1.0.
                 *
                 * Analog joystick input and GameMaker-specific mouse/
                 * fast-forward controls belong to the native runner.
                 */
                is GamepadElement.AnalogJoystick -> Unit

                is GamepadElement.MouseButton -> Unit

                is GamepadElement.FastForward -> Unit
            }
        }
    }
}

@Composable
private fun BoxWithConstraintsScope.placementForElement(
    element: GamepadElement
): Modifier {
    val referenceSize =
        if (maxWidth < maxHeight) {
            maxWidth
        } else {
            maxHeight
        }

    val size = referenceSize * element.scale.toFloat()

    val x =
        maxWidth * element.positionX.toFloat() -
            size / 2f

    val y =
        maxHeight * element.positionY.toFloat() -
            size / 2f

    return Modifier
        .offset(
            x = x,
            y = y
        )
        .size(size)
        .alpha(element.opacity.toFloat())
}

@Composable
private fun HtmlKeyButton(
    element: GamepadElement.Key,
    onKeyDown: (Int) -> Unit,
    onKeyUp: (Int) -> Unit,
    modifier: Modifier
) {
    val binding = element.binding as? InputBinding.Keyboard
        ?: return

    val label =
        element.label
            ?: htmlKeyLabel(binding.vk)

    Box(
        modifier = modifier
            .background(
                Color(0xAA222222),
                CircleShape
            )
            .pointerInput(binding.vk) {
                awaitEachGesture {
                    awaitFirstDown(
                        requireUnconsumed = false
                    )

                    onKeyDown(binding.vk)

                    try {
                        waitForUpOrCancellation()
                    } finally {
                        onKeyUp(binding.vk)
                    }
                }
            },
        contentAlignment = Alignment.Center
    ) {
        Text(
            text = label,
            color = Color.White,
            fontSize = 18.sp
        )
    }
}

