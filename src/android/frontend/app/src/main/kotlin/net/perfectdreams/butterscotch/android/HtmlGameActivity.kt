@Composable
private fun HtmlMenu(
    controlsVisible: Boolean,
    onResume: () -> Unit,
    onToggleControls: () -> Unit,
    onExit: () -> Unit
) {
    BackHandler {
        onResume()
    }

    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(
                Color.Black.copy(alpha = 0.75f)
            ),
        contentAlignment = Alignment.Center
    ) {
        Column(
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            HtmlMenuAction(
                text = "Resume",
                onClick = onResume
            )

            HtmlMenuAction(
                text = if (controlsVisible) {
                    "Hide Controls"
                } else {
                    "Show Controls"
                },
                onClick = onToggleControls
            )

            HtmlMenuAction(
                text = "Exit Game",
                onClick = onExit
            )
        }
    }
}

