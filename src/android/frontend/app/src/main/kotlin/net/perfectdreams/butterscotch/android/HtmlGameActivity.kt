/**
 * Tracks synthetic keyboard state for the WebView.
 *
 * Reference counting is important because two simultaneous fingers can
 * legally target the same keyboard binding. The key must only be released
 * after every pointer using that binding has released it.
 */
private class HtmlKeyState {

    private val references = HashMap<Int, Int>()

    fun press(
        webView: WebView,
        vk: Int
    ) {
        val oldCount = references[vk] ?: 0
        val newCount = oldCount + 1

        references[vk] = newCount

        if (oldCount == 0) {
            dispatch(webView, vk, true)
        }
    }

    fun release(
        webView: WebView,
        vk: Int
    ) {
        val oldCount = references[vk] ?: return
        val newCount = oldCount - 1

        if (newCount <= 0) {
            references.remove(vk)
            dispatch(webView, vk, false)
        } else {
            references[vk] = newCount
        }
    }

    fun releaseAll(
        webView: WebView?
    ) {
        if (webView == null) {
            references.clear()
            return
        }

        val keys = references.keys.toList()

        references.clear()

        for (vk in keys) {
            dispatch(webView, vk, false)
        }
    }

    fun clear() {
        references.clear()
    }

    private fun dispatch(
        webView: WebView,
        vk: Int,
        pressed: Boolean
    ) {
        val data = keyData(vk) ?: return

        val eventType =
            if (pressed) {
                "keydown"
            } else {
                "keyup"
            }

        val key = JSONObject.quote(data.key)
        val code = JSONObject.quote(data.code)

        val script = """
            (() => {
                const event = new KeyboardEvent("$eventType", {
                    key: $key,
                    code: $code,
                    bubbles: true,
                    cancelable: true
                });

                try {
                    Object.defineProperty(event, "keyCode", {
                        get: () => ${data.keyCode}
                    });

                    Object.defineProperty(event, "which", {
                        get: () => ${data.keyCode}
                    });

                    Object.defineProperty(event, "charCode", {
                        get: () => ${data.keyCode}
                    });
                } catch (_) {
                }

                window.dispatchEvent(event);

                document.dispatchEvent(event);

                if (document.body) {
                    document.body.dispatchEvent(event);
                }

                if (document.activeElement) {
                    document.activeElement.dispatchEvent(event);
                }
            })();
        """.trimIndent()

        webView.post {
            if (!webView.isAttachedToWindow) {
                return@post
            }

            webView.evaluateJavascript(
                script,
                null
            )
        }
    }

    private fun keyData(vk: Int): KeyData? {
        return when (vk) {
            37 -> KeyData("ArrowLeft", "ArrowLeft", 37)
            38 -> KeyData("ArrowUp", "ArrowUp", 38)
            39 -> KeyData("ArrowRight", "ArrowRight", 39)
            40 -> KeyData("ArrowDown", "ArrowDown", 40)

            13 -> KeyData("Enter", "Enter", 13)
            27 -> KeyData("Escape", "Escape", 27)
            32 -> KeyData(" ", "Space", 32)
            8 -> KeyData("Backspace", "Backspace", 8)
            9 -> KeyData("Tab", "Tab", 9)

            16 -> KeyData("Shift", "ShiftLeft", 16)
            17 -> KeyData("Control", "ControlLeft", 17)
            18 -> KeyData("Alt", "AltLeft", 18)

            in 65..90 -> {
                val letter =
                    ('A'.code + (vk - 65)).toChar()

                KeyData(
                    key = letter.toString().lowercase(),
                    code = "Key$letter",
                    keyCode = vk
                )
            }

            in 48..57 -> {
                val number =
                    ('0'.code + (vk - 48)).toChar()

                KeyData(
                    key = number.toString(),
                    code = "Digit$number",
                    keyCode = vk
                )
            }

            else -> null
        }
    }

    private data class KeyData(
        val key: String,
        val code: String,
        val keyCode: Int
    )
}
